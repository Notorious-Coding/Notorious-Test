using System.Reflection;
using NotoriousTest.Core.Environments;
using NotoriousTest.Core.Logger;
using NotoriousTest.Core.Registry;
using NotoriousTest.Core.Runtime;
using NotoriousTest.Core.Watchdog;
using NotoriousTest.Sample.MSTest.Infrastructures;
using NotoriousTest.Web.AspNetCore;

namespace NotoriousTest.Sample.MSTest.Environments;

// In fact, this is a test fixture (MSTest terminology: ClassInitialize/ClassCleanup).
public class TestEnvironment : EnvironmentBase
{
    public TestEnvironment(EnvironmentSettings settings,
        IWatchDog watchDog,
        IRegistry registry,
        IRuntime runtime,
        ITestLogger logger,
        IServiceProvider serviceProvider) : base(settings,
        watchDog,
        registry,
        runtime,
        logger,
        serviceProvider)
    {
    }

    protected override Assembly CurrentAssembly => Assembly.GetExecutingAssembly();

    // This is called at the start of the test campaign
    public override async Task ConfigureEnvironment(InfrastructureListBuilder builder)
    {
        // Adding all infrastructure needed for the test
        // Every environment generate an EnvironmentId that is unique for each test campaign
        builder.Add<SqlServerInfrastructure>();

        // Starts the API from its Program class in memory,
        // and gives it the configuration generated by other infrastructures. No class to write.
        // To override WebApplicationFactory methods, inherit from AspNetCoreWebApplication<Program>
        // and add it with builder.ThenAdd<AspNetCoreWebApplicationInfrastructure<MyWebApplication, Program>>().
        // It is added in a new group, so it starts once the database is running.
        builder.ThenAddAspNetWebApplication<Program>();
    }
}
